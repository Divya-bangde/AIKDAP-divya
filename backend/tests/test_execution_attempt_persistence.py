@pytest.mark.asyncio
async def test_duplicate_container_name_rejected(session, project):
    job = await _make_job(session, project)
    shared_name = _container_name_for(uuid.uuid4())

    payload_a = ExecutionAttemptCreate(execution_job_id=job.id, attempt_number=1, container_name=shared_name)
    await ExecutionAttemptRepository(session).create(_attempt_from_create(payload_a))
    await session.commit()

    # The violating insert runs in its own short-lived session, closed
    # (and its aborted transaction implicitly rolled back) on the way out
    # of the `async with` block regardless of the exception -- keeps the
    # primary `session` fixture's connection/transaction state untouched
    # by the failure, avoiding the known module-level-engine +
    # function-scoped-event-loop pool fragility a mid-test failed-flush-
    # then-continue on the SAME session can trigger.
    payload_b = ExecutionAttemptCreate(execution_job_id=job.id, attempt_number=2, container_name=shared_name)
    async with async_session_factory() as violating_session:
        with pytest.raises(IntegrityError):
            await ExecutionAttemptRepository(violating_session).create(_attempt_from_create(payload_b))

    # The original attempt is unaffected, verified via its own fresh session.
    async with async_session_factory() as verify_session:
        result = await verify_session.execute(
            select(ExecutionAttempt).where(ExecutionAttempt.container_name == shared_name)
        )
        rows = result.scalars().all()
    assert len(rows) == 1
    assert rows[0].attempt_number == 1


