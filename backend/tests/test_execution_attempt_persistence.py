def _matmul_job_create(project: Project) -> ExecutionJobCreate:
    return ExecutionJobCreate(
        project_id=project.id,
        owner_id=project.owner_id,
        experiment_plan_id=uuid.uuid4(),
        experiment_plan_version=1,
        capability=ExecutionCapability.ARRAY_COMPUTE,
        operation=ExecutionOperation.MATMUL,
        resource_class=ResourceClass.CLASS_ARRAY,
        parameters={},
        input_asset_ids=[],
    )


def _job_from_create(payload: ExecutionJobCreate, *, status: ExecutionJobStatus = ExecutionJobStatus.PENDING) -> ExecutionJob:
    data = payload.model_dump()
    data["input_asset_ids"] = [str(asset_id) for asset_id in payload.input_asset_ids]
    return ExecutionJob(status=status, **data)


async def _make_job(session, project: Project) -> ExecutionJob:
    job = await ExecutionJobRepository(session).create(_job_from_create(_matmul_job_create(project)))
    await session.commit()
    return job


def _container_name_for(attempt_id: uuid.UUID) -> str:
    """A synthetic, deterministic string -- the exact shape a future
    service would compute (Phase 7B.12 Part 5), NOT generated by any code
    under test here. Persistence tests only care that whatever string is
    handed in round-trips exactly."""
    return f"aikdap-exec-{attempt_id}"


def _attempt_from_create(payload: ExecutionAttemptCreate) -> ExecutionAttempt:
    return ExecutionAttempt(**payload.model_dump())


